#!/usr/bin/env python3
"""Builds the embedded UI font of the Modern style: two static instances of Inter (Regular 400, SemiBold
600), subset to Latin plus the symbols the widgets use, written as C++ byte arrays to
src/ui/modern/InterFont.cpp. Run it from the repository root when the font or the symbol list changes; the
atlas in src/ui/modern/FontAtlas.cpp bakes the same code points (keep the two lists equal).

Needs fonttools:  pip install fonttools
Usage:  python3 tools/make_fonts.py third_party/inter/InterVariable.ttf
"""
import io
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2212, 0x00D7, 0x2192, 0x2190, 0x25B8, 0x25BE,
    0x2191, 0x2193]


def instance(path, weight):
    f = TTFont(path)
    f = instancer.instantiateVariableFont(f, {"wght": weight, "opsz": 14}, inplace=False)
    opts = subset.Options()
    opts.layout_features = []  # kerning and ligatures are not used by the atlas renderers
    opts.name_IDs = [1, 2]
    opts.notdef_outline = True
    opts.drop_tables += ["GSUB", "GPOS", "GDEF", "STAT", "MVAR", "HVAR", "avar", "fvar", "gvar", "cvar", "kern"]
    opts.glyph_names = False
    opts.hinting = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(f)
    out = io.BytesIO()
    f.save(out)
    return out.getvalue()


def emit(name, data, out):
    out.write("const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 24):
        out.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.write("};\nconst unsigned long %sSize = %d;\n\n" % (name, len(data)))


def main():
    src = sys.argv[1]
    regular, semibold = instance(src, 400), instance(src, 600)
    with open("src/ui/modern/InterFont.cpp", "w", newline="\n") as out:
        out.write("// Generated by tools/make_fonts.py from Inter (SIL Open Font License 1.1, third_party/inter/LICENSE.txt).\n")
        out.write("// Never edit by hand. Two static instances, Regular and SemiBold, subset to Latin and the UI symbols.\n")
        out.write("// clang-format off\n")
        out.write("#include \"spux/ui/modern/InterFont.hpp\"\n\nnamespace spux::inline v1::ui::modern {\n\n")
        emit("kInterRegular", regular, out)
        emit("kInterSemiBold", semibold, out)
        out.write("} // namespace spux::inline v1::ui::modern\n")
        out.write("// clang-format on\n")
    print("regular %d bytes, semibold %d bytes" % (len(regular), len(semibold)))


main()
