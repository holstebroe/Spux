#!/usr/bin/env python3
"""Bakes a factory-preset folder into a C++ table for spux::presets::PresetLibrary.

    bake_presets.py <folder> <out.cpp> --symbol kBakedPresets [--namespace my::ns] [--extension .txt] [--check]

The folder holds a directory per group ("NN GROUP") with a file per preset ("NN NAME.txt"); the NN prefixes give
the order and are not part of the names (the same rules as PresetLibrary). With --check nothing is written and the
exit status says whether <out.cpp> is what baking the folder gives.
"""
import argparse, os, re, sys


def bake(folder, symbol, namespace, extension):
    rows = []
    for group in sorted(os.listdir(folder)):
        gdir = os.path.join(folder, group)
        if not os.path.isdir(gdir):
            continue
        gname = re.sub(r"^\d+ ", "", group)
        for f in sorted(os.listdir(gdir)):
            if not f.endswith(extension):
                continue
            name = re.sub(r"^\d+ ", "", f[: -len(extension)])
            with open(os.path.join(gdir, f), encoding="utf-8", newline="") as fh:
                text = fh.read().replace("\r", "").strip("\n")
            assert ')PRESET"' not in text, f
            rows.append(f'    {{ "{gname}", "{name}",\nR"PRESET({text})PRESET", {{}} }},')
    open_ns = "".join(f"namespace {n} {{\n" for n in namespace.split("::")) if namespace else ""
    close_ns = "".join(f"}} // namespace {n}\n" for n in reversed(namespace.split("::"))) if namespace else ""
    return ("// Generated by spux tools/bake_presets.py from the presets folder: do not edit.\n"
            '#include "spux/presets/PresetLibrary.hpp"\n\n' + open_ns +
            f"extern const std::vector<spux::presets::Preset> {symbol};\n"
            f"const std::vector<spux::presets::Preset> {symbol} = {{\n" + "\n".join(rows) + "\n};\n\n" + close_ns)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder")
    ap.add_argument("out")
    ap.add_argument("--symbol", required=True)
    ap.add_argument("--namespace", default="")
    ap.add_argument("--extension", default=".txt")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = bake(a.folder, a.symbol, a.namespace, a.extension)
    if a.check:
        ok = False
        if os.path.exists(a.out):
            with open(a.out, encoding="utf-8", newline="") as fh:
                ok = fh.read() == out
        print("baked table is up to date" if ok else f"{a.out} is out of date: bake {a.folder} again")
        sys.exit(0 if ok else 1)
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(out)


if __name__ == "__main__":
    main()
